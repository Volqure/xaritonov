# Шаг 1: Проверка нормировки
print("\n1) Проверяем условие нормировки: ∫ f(x) dx = 1")

print("   ∫_{-π/2}^{π/2} (2/π)·cos²(x) dx =")
print("   = (2/π) · ∫_{-π/2}^{π/2} cos²(x) dx")

print("   Используем: cos²(x) = (1 + cos2x)/2")
print("   ∫ cos²(x) dx = ∫ (1+cos2x)/2 dx = (1/2)·∫ dx + (1/2)·∫ cos2x dx")
print("   = x/2 + (sin2x)/4")

print("\n   Подставляем пределы от -π/2 до π/2:")
print("   (π/2)/2 + (sin π)/4 - [ (-π/2)/2 + (sin(-π))/4 ]")
print("   = π/4 + 0 - [ -π/4 + 0 ] = π/4 + π/4 = π/2")

print("\n   Тогда интеграл = (2/π) · (π/2) = 1")
