print("   J = [x²·sin2x / 2]_{-π/2}^{π/2} - ∫ (sin2x / 2)·2x dx")
print("   В подстановке sin2x при ±π/2 равен sin(±π) = 0, первое слагаемое = 0")
print("   J = -∫_{-π/2}^{π/2} x·sin2x dx")

print("\n   Интегрируем ∫ x·sin2x dx:")
print("   u = x, dv = sin2x dx, du = dx, v = -cos2x / 2")
print("   ∫ x·sin2x dx = -x·cos2x / 2 + ∫ cos2x / 2 dx = -x·cos2x / 2 + sin2x / 4")

print("\n   Подставляем пределы от -π/2 до π/2:")
print("   В π/2: sin π = 0, cos π = -1 → - (π/2)·(-1)/2 = π/4")
print("   В -π/2: sin(-π)=0, cos(-π)=-1 → - (-π/2)·(-1)/2 = -π/4")
print("   Разность: π/4 - (-π/4) = π/2")
print("   Значит ∫ x·sin2x dx = π/2")

print("\n   Тогда J = - (π/2) = -π/2")
print("   Делим на π: (1/π)·J = (1/π)·(-π/2) = -1/2")

print("\n   Собираем M[X²]:")
print("   M[X²] = π²/12 + (-1/2) = π²/12 - 1/2")

