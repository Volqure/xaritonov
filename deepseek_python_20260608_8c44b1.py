# -*- coding: utf-8 -*-
"""
Индивидуальное домашнее задание: Непрерывные случайные величины
Вариант 1
"""

import sympy as sp
import math

print("=" * 70)
print("ИНДИВИДУАЛЬНОЕ ДОМАШНЕЕ ЗАДАНИЕ")
print("Непрерывные случайные величины")
print("Вариант 1")
print("=" * 70)

# ----------------------------------------------------------------------
# ЗАДАЧА 1
# ----------------------------------------------------------------------
print("\n" + "=" * 70)
print("ЗАДАЧА 1")
print("=" * 70)
print("""Условие задачи:
Найти математическое ожидание и дисперсию случайной величины X,
если её плотность вероятностей:

    f(x) = (2/π) · cos²(x)

на интервале (-π/2, π/2) и равна нулю при |x| ≥ π/2.
""")

# Определяем символьную переменную
x = sp.Symbol('x', real=True)

# Плотность распределения
f1 = (2 / sp.pi) * sp.cos(x)**2

# Интервал
a1 = -sp.pi / 2
b1 = sp.pi / 2

print(f"\nПлотность распределения: f(x) = {sp.latex(f1)}")
print(f"Область определения: x ∈ [{sp.latex(a1)}, {sp.latex(b1)}]")

# ----------------------------------------------------------------------
# Шаг 1: Проверка условия нормировки (должно быть =1)
# ----------------------------------------------------------------------
print("\n" + "-" * 50)
print("ШАГ 1: Проверка нормировки плотности")
print("Условие: ∫_{-π/2}^{π/2} f(x) dx = 1")
print("-" * 50)

norm1 = sp.integrate(f1, (x, a1, b1))
print(f"∫ f(x) dx = {norm1.simplify()}")
if abs(norm1 - 1) < 1e-9:
    print("✓ Условие нормировки выполняется.")
else:
    print("✗ Ошибка: интеграл не равен 1.")

# ----------------------------------------------------------------------
# Шаг 2: Математическое ожидание M[X] = ∫ x·f(x) dx
# ----------------------------------------------------------------------
print("\n" + "-" * 50)
print("ШАГ 2: Математическое ожидание")
print("Формула: M[X] = ∫ x·f(x) dx")
print("-" * 50)

M1 = sp.integrate(x * f1, (x, a1, b1))
M1_simplified = M1.simplify()

print(f"M[X] = ∫ x·({sp.latex(f1)}) dx = {sp.latex(M1_simplified)}")

# Численное значение
M1_numeric = float(M1_simplified)
print(f"Численно: M[X] = {M1_numeric}")

# ----------------------------------------------------------------------
# Шаг 3: M[X²] = ∫ x²·f(x) dx
# ----------------------------------------------------------------------
print("\n" + "-" * 50)
print("ШАГ 3: Вычисление M[X²]")
print("Формула: M[X²] = ∫ x²·f(x) dx")
print("-" * 50)

M_X2_1 = sp.integrate(x**2 * f1, (x, a1, b1))
M_X2_1_simplified = M_X2_1.simplify()

print(f"M[X²] = ∫ x²·({sp.latex(f1)}) dx = {sp.latex(M_X2_1_simplified)}")

M_X2_1_numeric = float(M_X2_1_simplified)
print(f"Численно: M[X²] = {M_X2_1_numeric}")

# ----------------------------------------------------------------------
# Шаг 4: Дисперсия D[X] = M[X²] - (M[X])²
# ----------------------------------------------------------------------
print("\n" + "-" * 50)
print("ШАГ 4: Дисперсия")
print("Формула: D[X] = M[X²] − (M[X])²")
print("-" * 50)

D1 = M_X2_1_simplified - M1_simplified**2
D1_simplified = D1.simplify()

print(f"D[X] = {sp.latex(M_X2_1_simplified)} − ({sp.latex(M1_simplified)})²")
print(f"D[X] = {sp.latex(D1_simplified)}")

D1_numeric = float(D1_simplified)
print(f"Численно: D[X] = {D1_numeric}")

# Среднеквадратическое отклонение
sigma1 = sp.sqrt(D1_simplified)
print(f"σ[X] = √D[X] = {sp.latex(sigma1.simplify())} ≈ {float(sigma1)}")

# ----------------------------------------------------------------------
# ОТВЕТ ПО ЗАДАЧЕ 1
# ----------------------------------------------------------------------
print("\n" + "=" * 50)
print("ОТВЕТ (ЗАДАЧА 1):")
print("=" * 50)
print(f"Математическое ожидание M[X] = {M1_numeric}")
print(f"Дисперсия D[X] = {D1_numeric}")
print(f"Среднеквадратическое отклонение σ[X] ≈ {float(sigma1):.6f}")

# ----------------------------------------------------------------------
# ЗАДАЧА 2
# ----------------------------------------------------------------------
print("\n" + "=" * 70)
print("ЗАДАЧА 2")
print("=" * 70)
print("""Условие задачи:
Непрерывная случайная величина X задана плотностью распределения:

    f(x) = a·x    при 0 ≤ x ≤ 2
    f(x) = 0      при x < 0 или x > 2

Найти значение коэффициента a и определить математическое ожидание
и дисперсию случайной величины X.
""")

# Определяем символ a
a = sp.Symbol('a', real=True, positive=True)

# Плотность распределения для x от 0 до 2
f2 = a * x

# Интервал
a2 = 0
b2 = 2

print(f"\nПлотность распределения: f(x) = {sp.latex(f2)} при x∈[0,2]")

# ----------------------------------------------------------------------
# Шаг 1: Находим a из условия нормировки ∫ f(x) dx = 1
# ----------------------------------------------------------------------
print("\n" + "-" * 50)
print("ШАГ 1: Нахождение коэффициента a")
print("Условие нормировки: ∫₀² a·x dx = 1")
print("-" * 50)

norm_integral = sp.integrate(f2, (x, a2, b2))
print(f"∫₀² a·x dx = {norm_integral}")

# Решаем уравнение norm_integral = 1
a_value = sp.solve(norm_integral - 1, a)[0]
print(f"Решаем: {norm_integral} = 1  →  a = {a_value}")

# Подставляем a в плотность
f2_with_a = f2.subs(a, a_value)
print(f"Плотность распределения: f(x) = {sp.latex(f2_with_a)}")

# ----------------------------------------------------------------------
# Шаг 2: Математическое ожидание M[X] = ∫ x·f(x) dx
# ----------------------------------------------------------------------
print("\n" + "-" * 50)
print("ШАГ 2: Математическое ожидание")
print("Формула: M[X] = ∫ x·f(x) dx")
print("-" * 50)

M2 = sp.integrate(x * f2_with_a, (x, a2, b2))
M2_simplified = M2.simplify()

print(f"M[X] = ∫₀² x·({sp.latex(f2_with_a)}) dx = {sp.latex(M2_simplified)}")

M2_numeric = float(M2_simplified)
print(f"Численно: M[X] = {M2_numeric}")

# ----------------------------------------------------------------------
# Шаг 3: M[X²] = ∫ x²·f(x) dx
# ----------------------------------------------------------------------
print("\n" + "-" * 50)
print("ШАГ 3: Вычисление M[X²]")
print("Формула: M[X²] = ∫ x²·f(x) dx")
print("-" * 50)

M_X2_2 = sp.integrate(x**2 * f2_with_a, (x, a2, b2))
M_X2_2_simplified = M_X2_2.simplify()

print(f"M[X²] = ∫₀² x²·({sp.latex(f2_with_a)}) dx = {sp.latex(M_X2_2_simplified)}")

M_X2_2_numeric = float(M_X2_2_simplified)
print(f"Численно: M[X²] = {M_X2_2_numeric}")

# ----------------------------------------------------------------------
# Шаг 4: Дисперсия D[X] = M[X²] - (M[X])²
# ----------------------------------------------------------------------
print("\n" + "-" * 50)
print("ШАГ 4: Дисперсия")
print("Формула: D[X] = M[X²] − (M[X])²")
print("-" * 50)

D2 = M_X2_2_simplified - M2_simplified**2
D2_simplified = D2.simplify()

print(f"D[X] = {sp.latex(M_X2_2_simplified)} − ({sp.latex(M2_simplified)})²")
print(f"D[X] = {sp.latex(D2_simplified)}")

D2_numeric = float(D2_simplified)
print(f"Численно: D[X] = {D2_numeric}")

# Среднеквадратическое отклонение
sigma2 = sp.sqrt(D2_simplified)
print(f"σ[X] = √D[X] = {sp.latex(sigma2.simplify())} ≈ {float(sigma2):.6f}")

# ----------------------------------------------------------------------
# ОТВЕТ ПО ЗАДАЧЕ 2
# ----------------------------------------------------------------------
print("\n" + "=" * 50)
print("ОТВЕТ (ЗАДАЧА 2):")
print("=" * 50)
print(f"Коэффициент a = {a_value}")
print(f"Плотность распределения: f(x) = {sp.latex(f2_with_a)} при 0≤x≤2")
print(f"Математическое ожидание M[X] = {M2_numeric}")
print(f"Дисперсия D[X] = {D2_numeric}")
print(f"Среднеквадратическое отклонение σ[X] ≈ {float(sigma2):.6f}")

print("\n" + "=" * 70)
print("КОНЕЦ РЕШЕНИЯ")
print("=" * 70)